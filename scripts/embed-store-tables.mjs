/**
 * Regenerates core/src/Stores/Tables.php from the shared classification tables in spec/data-stores/.
 *
 * The tables are embedded unchanged so the published package needs no file outside `src/`. The unit
 * test `embedded data-store tables match spec/data-stores` (core/tests/StoreTablesTest.php) fails
 * when the copy and the spec differ; run this script (`composer embed-store-tables` in
 * adapters/php/core) to bring them back in line.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const spec = new URL('../../../../spec/data-stores/', import.meta.url);
const output = new URL('../src/Stores/Tables.php', import.meta.url);
// Cassandra and Cosmos DB have no PHP hook (see adapters/php/data-stores.md); their tables are embedded
// anyway so the parity test keeps the copy in step with the spec for every store of the batch.
const stores = ['redis', 'mongodb', 'dynamodb', 'cassandra', 'elasticsearch', 'cosmosdb', 'firestore'];

const constant = store => {
  // Re-serialise so the embedded text is canonical JSON whatever the spec file's formatting.
  const table = JSON.parse(readFileSync(new URL(`${store}.json`, spec), 'utf8'));
  return [
    `    /** The shared ${store} classification table, embedded unchanged from spec/data-stores/${store}.json. */`,
    `    private const ${store.toUpperCase()} = <<<'JSON'`,
    JSON.stringify(table, null, 2),
    'JSON;',
    '',
  ].join('\n');
};

const accessor = store => [
  `    /** @return array<string,mixed> The decoded ${store} table. */`,
  `    public static function ${store}(): array`,
  '    {',
  `        return self::decode(self::${store.toUpperCase()});`,
  '    }',
  '',
].join('\n');

const lines = [
  '<?php',
  '',
  '// Generated by core/scripts/embed-store-tables.mjs from spec/data-stores/. Do not edit by hand.',
  '// A unit test fails when this copy differs from the spec tables.',
  '',
  'declare(strict_types=1);',
  '',
  'namespace Sendproof\\Core\\Stores;',
  '',
  '/** The shared write-classification tables of spec/data-stores.md, embedded so the package needs no spec files. */',
  'final class Tables',
  '{',
  ...stores.map(constant),
  ...stores.map(accessor),
  '    /** @return array<string,mixed> */',
  '    private static function decode(string $json): array',
  '    {',
  '        /** @var array<string,mixed> */',
  '        return json_decode($json, true, 512, JSON_THROW_ON_ERROR);',
  '    }',
  '}',
  '',
];
writeFileSync(output, lines.join('\n'));
